// Regenerates src/seedIndex.ts from evals/seeds: the planner needs each seed's
// id, cell, and OWASP mapping, embedded so it works where evals/ is not on disk.
// Run: npm run seeds:sync -w packages/planner  (a test fails when it is stale).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const seedDir = join(here, '..', '..', '..', 'evals', 'seeds')

export function readSeedIndex(dir = seedDir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .flatMap((f) => {
      const parsed = JSON.parse(readFileSync(join(dir, f), 'utf8'))
      const cases = Array.isArray(parsed) ? parsed : parsed.cases
      return cases.map((c) => ({
        id: c.id,
        category: c.category,
        subcategory: c.subcategory,
        owasp_llm_ids: c.owasp_llm_ids,
        owasp_ids: c.owasp_ids,
      }))
    })
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const body = JSON.stringify(readSeedIndex(), null, 2)
  writeFileSync(
    join(here, '..', 'src', 'seedIndex.ts'),
    `// GENERATED by scripts/sync-seed-index.mjs from evals/seeds — do not edit.\n` +
      `import type { PlanningSeed } from './seeds.js'\n\n` +
      `export const SEED_INDEX: readonly PlanningSeed[] = ${body}\n`,
  )
  console.log('wrote src/seedIndex.ts')
}
